package com.mycompany.sefolopart1;

import java.io.File;

import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.*;

public class MessageTest {

    // ---------- Test data from the assignment ----------

    // Test Case 1
    private final String recipient1 = "+27718693002";
    private final String text1 = "Hi Mike, can you join us for dinner tonight?";

    // Test Case 2
    private final String recipient2 = "08575975889";
    private final String text2 = "Hi Keegan, did you receive the payment?";


    // ---------- The message should not be more than 250 characters ----------

    @Test
    public void testMessageLength_Success() {
        Message message = new Message();
        assertEquals("Message ready to send.", message.checkMessageLengthStatus(text1));
    }

    @Test
    public void testMessageLength_Failure() {
        Message message = new Message();

        // 260 characters, so it is 10 too long
        String longText = "a".repeat(260);

        assertEquals("Message exceeds 250 characters by 10; please reduce the size.",
                message.checkMessageLengthStatus(longText));
    }


    // ---------- The recipient number is correctly formatted ----------

    @Test
    public void testRecipientCell_Success() {
        Message message = new Message();
        assertEquals("Cell phone number successfully captured.", message.checkRecipientCell(recipient1));
    }

    @Test
    public void testRecipientCell_Failure() {
        Message message = new Message();
        assertEquals("Cell phone number is incorrectly formatted or does not contain an international code. Please correct the number and try again.",
                message.checkRecipientCell(recipient2));
    }


    // ---------- Message hash is correct ----------

    @Test
    public void testMessageHash_TestCase1() {
        // the ID and the message number are fixed so the hash can be predicted
        Message message = new Message("0012345678", 0, recipient1, text1);
        assertEquals("00:0:HITONIGHT", message.createMessageHash());
    }

    @Test
    public void testMessageHash_Loop() {
        // every message is checked in a loop: ID, message number, message, expected hash
        String[] ids = {"0012345678", "0087654321", "1234567890", "9876543210"};
        int[] numbers = {0, 1, 2, 3};
        String[] texts = {text1, text2, "Okay see you tomorrow at nine", "Hello"};
        String[] expected = {"00:0:HITONIGHT", "00:1:HIPAYMENT", "12:2:OKAYNINE", "98:3:HELLOHELLO"};

        for (int i = 0; i < ids.length; i++)
        {
            Message message = new Message(ids[i], numbers[i], recipient1, texts[i]);
            assertEquals(expected[i], message.createMessageHash());
        }
    }


    // ---------- Message ID is created ----------

    @Test
    public void testMessageID_Created() {
        Message message = new Message("0012345678", 0, recipient1, text1);
        assertEquals("Message ID generated: 0012345678", message.returnMessageID());
    }

    @Test
    public void testMessageID_AutoGenerated() {
        // an auto generated ID must be no more than ten characters
        Message message = new Message(recipient1, text1);

        assertTrue(message.checkMessageID());
        assertTrue(message.returnMessageID().startsWith("Message ID generated: "));
        assertEquals(22 + 10, message.returnMessageID().length());
    }


    // ---------- MessageSent: send, disregard, store ----------

    @Test
    public void testSentMessage_Send() {
        Message message = new Message(recipient1, text1);
        assertEquals("Message successfully sent.", message.sentMessage(1));
    }

    @Test
    public void testSentMessage_Disregard() {
        Message message = new Message(recipient2, text2);
        assertEquals("Press 0 to delete the message.", message.sentMessage(2));
    }

    @Test
    public void testSentMessage_Store() {
        Message message = new Message(recipient1, text1);
        assertEquals("Message successfully stored.", message.sentMessage(3));

        // storing the message also writes the JSON file
        assertTrue(new File("StoredMessages.json").exists());
    }


    // ---------- Return total number sent ----------

    @Test
    public void testReturnTotalMessages() {
        int before = Message.returnTotalMessages();

        // Test Case 1 - Send
        Message message1 = new Message(recipient1, text1);
        message1.sentMessage(1);
        assertEquals(before + 1, Message.returnTotalMessages());

        // Test Case 2 - Discard, so the total does not change
        Message message2 = new Message(recipient2, text2);
        message2.sentMessage(2);
        assertEquals(before + 1, Message.returnTotalMessages());
    }

    @Test
    public void testPrintMessages_ContainsSentMessage() {
        Message message = new Message(recipient1, text1);
        message.sentMessage(1);

        assertTrue(message.printMessages().contains(text1));
    }
}